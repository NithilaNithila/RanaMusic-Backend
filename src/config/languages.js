const sanitizeLang = (raw) =>
  raw && LANGUAGES[raw] ? raw : "hi";

// Upstream Saavn tags songs with these lowercase language names.
const LANGUAGE_NAMES = {
  en: ["english"],
  hi: ["hindi"],
  ta: ["tamil"],
  te: ["telugu"],
  ml: ["malayalam"],
  kn: ["kannada"],
};

// Returns the language code only when it is a supported one (no "hi"
// default) — used by free-form searches where omitting the param means no
// filtering at all.
const isLangValue = (raw) => (raw && LANGUAGE_NAMES[raw] ? raw : null);

// True when an item (track/album) belongs to the given language code. Items
// without a language tag are rejected so a filtered search stays accurate.
const isInLanguage = (item, lang) => {
  const names = lang && LANGUAGE_NAMES[lang];
  const value = ((item && item.language) || "").toLowerCase().trim();
  if (!names || !value) return false;
  return names.some((name) => value === name || value.includes(name));
};

